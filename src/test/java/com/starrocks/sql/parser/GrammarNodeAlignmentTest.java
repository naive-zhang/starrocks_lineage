package com.starrocks.sql.parser;

import org.antlr.v4.runtime.tree.ParseTree;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import java.lang.reflect.Method;
import java.util.Arrays;
import java.util.Set;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Architect iron rule #1: the visitor node matrix of Stage 3 must use the method names generated from the official
 * branch-3.1 grammar. The combined grammar is named {@code StarRocks}, hence the base visitor is
 * {@code StarRocksBaseVisitor} (not {@code StarRocksParserBaseVisitor}).
 */
class GrammarNodeAlignmentTest {

    private static final Set<String> VISITOR_METHODS = Arrays.stream(StarRocksBaseVisitor.class.getDeclaredMethods())
            .map(Method::getName)
            .collect(Collectors.toSet());

    @ParameterizedTest
    @ValueSource(strings = {
        "visitQueryStatement", "visitQueryRelation", "visitWithClause", "visitCommonTableExpression",
        "visitQueryNoWith", "visitQueryPrimaryDefault", "visitQueryWithParentheses", "visitSetOperation",
        "visitQuerySpecification", "visitFrom", "visitDual", "visitRelations", "visitRelation",
        "visitTableAtom", "visitSubqueryWithAlias", "visitInlineTable", "visitTableFunction",
        "visitNormalizedTableFunction", "visitParenthesizedRelation", "visitJoinRelation", "visitJoinCriteria",
        "visitSelectSingle", "visitSelectAll", "visitColumnRef", "visitDereference", "visitLambdaFunctionExpr",
        "visitExists", "visitSubqueryExpression", "visitInSubquery", "visitAggregationFunctionCall",
        "visitWindowFunctionCall", "visitSimpleFunctionCall", "visitOver", "visitSortItem", "visitSearchedCase",
        "visitSimpleCase", "visitSingleGroupingSet", "visitRollup", "visitCube", "visitMultipleGroupingSets",
        "visitInsertStatement", "visitCreateTableAsSelectStatement", "visitCreateViewStatement",
        "visitAlterViewStatement", "visitCreateMaterializedViewStatement", "visitUpdateStatement",
        "visitDeleteStatement", "visitSubmitTaskStatement"
    })
    void officialVisitorMethodExists(String method) {
        assertTrue(VISITOR_METHODS.contains(method), method + " must exist in StarRocksBaseVisitor");
    }

    @ParameterizedTest
    @ValueSource(strings = {
        "visitFromClause", "visitUnnestRelation", "visitLateralView", "visitDereferenceExpression"
    })
    void namesThatDoNotExistInBranch31(String method) {
        assertFalse(VISITOR_METHODS.contains(method),
                method + " is not generated by branch-3.1; see docs/stage1-architecture.md R-01");
    }

    @Test
    void unnestIsATableFunctionAndLateralIsAKeywordOfRelations() {
        StarRocksSqlParser.ParsedSql parsed = new StarRocksSqlParser()
                .parse("SELECT t.id, u.c1 FROM db.t AS t, LATERAL UNNEST(t.arr1, t.arr2) AS u(c1, c2)");
        StarRocksParser.QueryPrimaryDefaultContext primary = (StarRocksParser.QueryPrimaryDefaultContext)
                parsed.getStatements().get(0).queryStatement().queryRelation().queryNoWith().queryPrimary();
        StarRocksParser.FromContext from = (StarRocksParser.FromContext) primary.querySpecification().fromClause();
        StarRocksParser.RelationsContext relations = from.relations();
        assertEquals(2, relations.relation().size());
        assertTrue(relations.LATERAL().size() == 1);
        ParseTree unnest = relations.relation(1).relationPrimary();
        StarRocksParser.TableFunctionContext tf = assertInstanceOf(StarRocksParser.TableFunctionContext.class, unnest);
        assertEquals("UNNEST", tf.qualifiedName().getText().toUpperCase());
        assertEquals(2, tf.expressionList().expression().size());
        assertEquals("u", tf.alias.getText());
        assertEquals(2, tf.columnAliases().identifier().size());
    }
}
